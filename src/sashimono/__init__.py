#: numpy の行列計算（OpenBLAS）が使うスレッドの数の上限（#454）
#:
#: OpenBLAS は読み込んだ時点で、スレッド 1 本につき 30 MB 前後の作業の領域をコミットする
#: 論理 20 コアの機械（Core Ultra 7 265KF）では numpy を読むだけで 618 MB になり、アプリの
#: コミットの 8 割を占めていた 別のプロセスの子（控え・解析・書き出し #440 #453）も 1 本ごとに
#: 同じだけ取る 実際に載るのは 10 MB ほどだが、コミットの上限（物理メモリ + ページファイル）を
#: 食い、メモリの少ない機械ではほかのアプリの確保が断られる
#:
#: アプリの numpy は小さな配列ばかりで、行列の掛け算の重い所は無い 800 x 800 の掛け算 5 回は
#: 既定 75 ms 4 本 30 ms 1 本 111 ms（コミットは 618 / 104 / 8 MB）だったので 4 本にする
#: 本人が環境変数で決めていればそちらを使う
#:
#: パッケージの頭に置くのは、numpy より先に読まれる所がここしか無いから 子のプロセスも、
#: 渡された仕事を解く前に必ずここを通る（環境変数は親から受け継ぐが、配布版の子は exe を
#: 頭から読み直す）
BLAS_THREADS = 4

_os.environ.setdefault("OPENBLAS_NUM_THREADS", str(BLAS_THREADS))
